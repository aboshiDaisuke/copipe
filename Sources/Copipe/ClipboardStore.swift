import AppKit
import CryptoKit

/// クリップボードを監視して履歴・ピンボードを保存・管理する
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published private(set) var pinboards: [Pinboard] = []
    /// この日時まで記録を止める（distantFuture なら再開するまで）
    @Published private(set) var pausedUntil: Date?

    var isPaused: Bool { (pausedUntil ?? .distantPast) > Date() }

    /// 保存期間に関係なく、これを超えた古い履歴は消す（ピンボードの項目は除く）
    let maxItems = 2000
    /// これより大きいクリップボードは丸ごとは保存しない
    private let maxRawSize = 50_000_000

    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let imageCache = NSCache<NSString, NSImage>()

    private let baseDir: URL
    private let imagesDir: URL
    private let rawDir: URL
    private let historyURL: URL
    private let pinboardsURL: URL

    /// パスワード管理アプリなどが「機密」と付けてくる型
    private static let confidentialTypes: Set<String> = ["org.nspasteboard.ConcealedType", "com.agilebits.onepassword"]
    /// 他のアプリが一時的に作ったデータに付く型
    private static let transientTypes: Set<String> = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    /// コピーを記録したときに呼ぶ（ペーストスタックがためるため）
    var onCapture: ((ClipItem) -> Void)?

    typealias Source = (appName: String?, bundleID: String?)

    init() {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        baseDir = support.appendingPathComponent("Copipe", isDirectory: true)
        imagesDir = baseDir.appendingPathComponent("images", isDirectory: true)
        rawDir = baseDir.appendingPathComponent("raw", isDirectory: true)
        historyURL = baseDir.appendingPathComponent("history.json")
        pinboardsURL = baseDir.appendingPathComponent("pinboards.json")
        try? FileManager.default.createDirectory(at: imagesDir, withIntermediateDirectories: true)
        try? FileManager.default.createDirectory(at: rawDir, withIntermediateDirectories: true)
        load()
        migratePinnedItems()
        trim()
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    // MARK: - 監視

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        guard !isPaused else { return }

        let types = Set((pb.types ?? []).map(\.rawValue))
        if Preferences.ignoreConfidential && !types.isDisjoint(with: Self.confidentialTypes) { return }
        if Preferences.ignoreTransient && !types.isDisjoint(with: Self.transientTypes) { return }

        let front = NSWorkspace.shared.frontmostApplication
        if let id = front?.bundleIdentifier, Preferences.ignoredApps.contains(id) { return }
        guard let item = makeItem(from: pb, source: (front?.localizedName, front?.bundleIdentifier)) else { return }
        let stored = addToHistory(item)
        Sound.copied()
        onCapture?(stored)
    }

    /// クリップボードの中身から項目を作る（画像・丸ごとのデータはファイルに保存する）
    private func makeItem(from pb: NSPasteboard, source: Source, date: Date = Date(),
                          pinboardID: UUID? = nil, title: String? = nil) -> ClipItem? {
        let raw = captureRaw(pb)
        var kind: ClipKind
        var text: String?
        var imageName: String?
        var filePaths: [String]?
        var signature: String

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            kind = .file
            filePaths = urls.map(\.path)
            signature = "f:" + urls.map(\.path).joined(separator: "\n")
        } else if let string = pb.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard string.utf8.count < 2_000_000 else { return nil }
            kind = Self.isLink(string) ? .link : .text
            text = string
            signature = "t:" + string
        } else if let image = NSImage(pasteboard: pb), let png = image.pngData() {
            kind = .image
            let name = Self.hash(png) + ".png"
            let url = imagesDir.appendingPathComponent(name)
            if !FileManager.default.fileExists(atPath: url.path) { try? png.write(to: url) }
            imageName = name
            signature = "i:" + Self.hash(png)
        } else if let raw {
            // 文字や画像として読めないアプリ独自のデータ（Final Cut Pro・Filmora の素材など）
            kind = .other
            var all = Data()
            for entry in raw.items.joined() { all.append(entry.data) }
            signature = "r:" + Self.hash(all)
        } else {
            return nil
        }

        return ClipItem(id: UUID(), kind: kind, text: text, imageName: imageName, filePaths: filePaths,
                        rawName: raw.flatMap(saveRaw), rawSize: raw?.totalSize,
                        sourceAppName: source.appName, sourceBundleID: source.bundleID,
                        date: date, signature: signature, pinboardID: pinboardID, title: title)
    }

    private func captureRaw(_ pb: NSPasteboard) -> RawPasteboard? {
        var items: [[RawPasteboard.Entry]] = []
        var total = 0
        for item in pb.pasteboardItems ?? [] {
            var entries: [RawPasteboard.Entry] = []
            for type in item.types where !type.rawValue.contains("promised") {
                guard let data = item.data(forType: type) else { continue }
                total += data.count
                if total > maxRawSize { return nil }
                entries.append(.init(type: type.rawValue, data: data))
            }
            if !entries.isEmpty { items.append(entries) }
        }
        return items.isEmpty ? nil : RawPasteboard(items: items)
    }

    private static func hash(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    private static func isLink(_ s: String) -> Bool {
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.contains(where: \.isWhitespace), let url = URL(string: t) else { return false }
        return ["http", "https"].contains(url.scheme?.lowercased() ?? "") && url.host != nil
    }

    /// 履歴の先頭に入れる。同じ内容が既にあればそれを先頭に移し、丸ごとのデータだけ新しいものにする
    @discardableResult
    private func addToHistory(_ item: ClipItem) -> ClipItem {
        let stored: ClipItem
        if let idx = items.firstIndex(where: { $0.pinboardID == nil && $0.signature == item.signature }) {
            var existing = items.remove(at: idx)
            existing.date = item.date
            existing.sourceAppName = item.sourceAppName
            existing.sourceBundleID = item.sourceBundleID
            if item.rawName != nil {
                removeRawFile(of: existing)
                existing.rawName = item.rawName
                existing.rawSize = item.rawSize
            }
            items.insert(existing, at: 0)
            stored = existing
        } else {
            items.insert(item, at: 0)
            stored = item
            trim()
        }
        save()
        return stored
    }

    private func trim() {
        var count = 0
        let limit = Retention.current.days.map { Date().addingTimeInterval(-Double($0) * 86_400) }
        var removed: [ClipItem] = []
        items.removeAll { item in
            guard item.pinboardID == nil else { return false }
            count += 1
            if count > maxItems || (limit.map { item.date < $0 } ?? false) {
                removed.append(item)
                return true
            }
            return false
        }
        removed.forEach(removeFiles)
        if !removed.isEmpty { pruneLinkPreviews() }
    }

    /// 消えたリンクの題名・画像も消す
    private func pruneLinkPreviews() {
        LinkPreviews.shared.prune(keeping: Set(items.compactMap { $0.kind == .link ? $0.text : nil }))
    }

    // MARK: - 操作

    func pause(for interval: TimeInterval?) {
        pausedUntil = interval.map { Date().addingTimeInterval($0) } ?? .distantFuture
    }

    func resume() {
        pausedUntil = nil
    }

    func setRetention(_ retention: Retention) {
        Retention.current = retention
        trim()
        save()
    }

    /// 「新しいテキストアイテム」で入力した文字を履歴に入れる
    func addManualText(_ text: String) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        addToHistory(ClipItem(id: UUID(), kind: .text, text: text, sourceAppName: "Copipe",
                              sourceBundleID: Bundle.main.bundleIdentifier, date: Date(), signature: "t:" + text))
    }

    /// 履歴の項目をクリップボードに戻す（自分自身の書き込みは記録しない）
    /// plainText が true なら書式を外して文字だけにする
    /// moveToTop が false なら履歴の並びを変えない（ペーストスタック用）
    func copyToPasteboard(_ item: ClipItem, plainText: Bool = false, moveToTop: Bool = true) {
        let pb = NSPasteboard.general
        write(item, to: pb, plainText: plainText)
        lastChangeCount = pb.changeCount
        if moveToTop && item.pinboardID == nil { self.moveToTop(item) }
    }

    /// 複数の項目をまとめてクリップボードに入れる（文字だけなら改行でつなぐ）
    func copyToPasteboard(_ list: [ClipItem], plainText: Bool = false) {
        if list.count == 1 { copyToPasteboard(list[0], plainText: plainText) }
        guard list.count > 1 else { return }
        let pb = NSPasteboard.general
        pb.clearContents()
        if list.allSatisfy({ $0.text != nil }) {
            pb.setString(list.compactMap(\.text).joined(separator: "\n"), forType: .string)
        } else {
            pb.writeObjects(list.flatMap { pasteboardItems(for: $0, plainText: plainText) })
        }
        lastChangeCount = pb.changeCount
    }

    /// 項目の中身を書き込み用に作る（丸ごとのデータがあればそのまま、なければ種類ごとに）
    /// 貼り付け・まとめてコピー・引っぱり出しで使う。plainText が true なら文字は書式なしにする
    func pasteboardItems(for item: ClipItem, plainText: Bool = false) -> [NSPasteboardItem] {
        if !(plainText && item.text != nil), let raw = loadRaw(of: item) { return pasteboardItems(from: raw) }
        switch item.kind {
        case .text, .link:
            let pbItem = NSPasteboardItem()
            pbItem.setString(item.text ?? "", forType: .string)
            if item.kind == .link, let url = item.openURL { pbItem.setString(url.absoluteString, forType: .URL) }
            return [pbItem]
        case .image:
            guard let url = imageURL(for: item), let png = try? Data(contentsOf: url) else { return [] }
            let pbItem = NSPasteboardItem()
            pbItem.setData(png, forType: .png)
            if let tiff = image(for: item)?.tiffRepresentation { pbItem.setData(tiff, forType: .tiff) }
            return [pbItem]
        case .file:
            return (item.filePaths ?? []).map { path in
                let pbItem = NSPasteboardItem()
                pbItem.setString(URL(fileURLWithPath: path).absoluteString, forType: .fileURL)
                return pbItem
            }
        case .other:
            return []
        }
    }

    private func write(_ item: ClipItem, to pb: NSPasteboard, plainText: Bool) {
        pb.clearContents()
        if let raw = loadRaw(of: item), !(plainText && item.text != nil) {
            // コピーしたときのデータを全形式そのまま戻す
            write(raw, to: pb)
            return
        }
        switch item.kind {
        case .text, .link:
            pb.setString(item.text ?? "", forType: .string)
        case .image:
            if let image = image(for: item) { pb.writeObjects([image]) }
        case .file:
            pb.writeObjects((item.filePaths ?? []).map { NSURL(fileURLWithPath: $0) })
        case .other:
            break
        }
    }

    private func write(_ raw: RawPasteboard, to pb: NSPasteboard) {
        pb.writeObjects(pasteboardItems(from: raw))
    }

    private func pasteboardItems(from raw: RawPasteboard) -> [NSPasteboardItem] {
        raw.items.map { entries in
            let pasteboardItem = NSPasteboardItem()
            for entry in entries {
                pasteboardItem.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.type))
            }
            return pasteboardItem
        }
    }

    private func moveToTop(_ item: ClipItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        var moved = items.remove(at: idx)
        moved.date = Date()
        items.insert(moved, at: 0)
        save()
    }

    func delete(_ item: ClipItem) {
        delete([item])
    }

    func delete(_ list: [ClipItem]) {
        let ids = Set(list.map(\.id))
        items.removeAll { ids.contains($0.id) }
        list.forEach(removeFiles)
        pruneLinkPreviews()
        save()
    }

    /// 「編集」で書き換えた文字を保存する（書式などの丸ごとのデータは古くなるので捨てる）
    func updateText(of item: ClipItem, to text: String) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        removeRawFile(of: items[idx])
        items[idx].rawName = nil
        items[idx].rawSize = nil
        items[idx].text = text
        items[idx].kind = Self.isLink(text) ? .link : .text
        items[idx].signature = "t:" + text
        pruneLinkPreviews()
        save()
    }

    /// 自分で名前を付ける（nil なら外す）
    func rename(_ item: ClipItem, to title: String?) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[idx].title = title
        save()
    }

    /// 同じ内容の項目をすぐ隣に作る
    func duplicate(_ item: ClipItem) {
        guard let idx = items.firstIndex(where: { $0.id == item.id }) else { return }
        items.insert(copy(of: item, pinboardID: item.pinboardID), at: idx + 1)
        save()
    }

    /// ピンボードの中で並べ替える（引っぱった項目を target の位置に動かす）
    func move(_ draggedID: UUID, to targetID: UUID) {
        guard let from = items.firstIndex(where: { $0.id == draggedID }),
              let to = items.firstIndex(where: { $0.id == targetID }), from != to,
              items[from].pinboardID != nil, items[from].pinboardID == items[to].pinboardID else { return }
        let moved = items.remove(at: from)
        items.insert(moved, at: to)
        save()
    }

    private func copy(of item: ClipItem, pinboardID: UUID?) -> ClipItem {
        ClipItem(id: UUID(), kind: item.kind, text: item.text, imageName: item.imageName,
                 filePaths: item.filePaths, rawName: duplicateRawFile(of: item), rawSize: item.rawSize,
                 sourceAppName: item.sourceAppName, sourceBundleID: item.sourceBundleID,
                 date: Date(), signature: item.signature, pinboardID: pinboardID, title: item.title)
    }

    /// クリップボードの履歴を消す（ピンボードの項目は残す）
    func clearHistory() {
        let removed = items.filter { $0.pinboardID == nil }
        items.removeAll { $0.pinboardID == nil }
        removed.forEach(removeFiles)
        pruneLinkPreviews()
        save()
    }

    // MARK: - ピンボード

    @discardableResult
    func createPinboard(name: String, color: Int? = nil) -> Pinboard {
        let board = Pinboard(id: UUID(), name: name,
                             color: color ?? Pinboard.palette[pinboards.count % Pinboard.palette.count])
        pinboards.append(board)
        savePinboards()
        return board
    }

    func renamePinboard(_ board: Pinboard, to name: String) {
        guard let idx = pinboards.firstIndex(where: { $0.id == board.id }) else { return }
        pinboards[idx].name = name
        savePinboards()
    }

    func setColor(of board: Pinboard, to color: Int) {
        guard let idx = pinboards.firstIndex(where: { $0.id == board.id }) else { return }
        pinboards[idx].color = color
        savePinboards()
    }

    func deletePinboard(_ board: Pinboard) {
        let removed = items.filter { $0.pinboardID == board.id }
        items.removeAll { $0.pinboardID == board.id }
        removed.forEach(removeFiles)
        pinboards.removeAll { $0.id == board.id }
        pruneLinkPreviews()
        savePinboards()
        save()
    }

    /// ピンボードに入っている内容 → そのピンボードの色（左のピンボードを優先）
    func pinboardColorsBySignature() -> [String: Int] {
        var result: [String: Int] = [:]
        for board in pinboards {
            for item in items where item.pinboardID == board.id && result[item.signature] == nil {
                result[item.signature] = board.color
            }
        }
        return result
    }

    /// 項目をピンボードに追加する（履歴の項目はそのまま残し、コピーを入れる）
    func add(_ item: ClipItem, to board: Pinboard) {
        guard !items.contains(where: { $0.pinboardID == board.id && $0.signature == item.signature }) else { return }
        // ピンボードの中では、追加したものが右端に並ぶ
        items.append(copy(of: item, pinboardID: board.id))
        save()
    }

    /// ⌘P: 履歴の項目は最初のピンボードに追加、ピンボードの項目はピンボードから外す
    func togglePin(_ item: ClipItem) {
        if item.pinboardID != nil {
            delete(item)
        } else {
            add(item, to: pinboards.first ?? createPinboard(name: "ピン留め", color: Pinboard.palette[0]))
        }
    }

    /// 旧バージョンでピン留めした項目を「ピン留め」ピンボードに移す
    private func migratePinnedItems() {
        guard items.contains(where: { $0.pinned && $0.pinboardID == nil }) else { return }
        let board = pinboards.first { $0.name == "ピン留め" } ?? createPinboard(name: "ピン留め", color: Pinboard.palette[0])
        for idx in items.indices where items[idx].pinned && items[idx].pinboardID == nil {
            items[idx].pinboardID = board.id
            items[idx].pinned = false
        }
        save()
    }

    // MARK: - Paste からの読み込み

    /// 読み込み用の作業クリップボード（本物のクリップボードには触らない）
    private lazy var importPasteboard = NSPasteboard(name: .init("jp.daisukeaboshi.copipe.import"))

    /// 他のアプリの履歴を1件取り込む。同じ内容が既に同じ場所にあれば何もしない
    @discardableResult
    func importItem(raw: RawPasteboard, source: Source, date: Date, pinboard: Pinboard?, title: String?) -> Bool {
        let pb = importPasteboard
        pb.clearContents()
        write(raw, to: pb)
        guard let item = makeItem(from: pb, source: source, date: date, pinboardID: pinboard?.id, title: title)
        else { return false }
        if items.contains(where: { $0.pinboardID == item.pinboardID && $0.signature == item.signature }) {
            removeRawFile(of: item)
            return false
        }
        items.append(item)
        return true
    }

    /// 読み込みが終わったら履歴を新しい順に並べ直して保存する
    func finishImport() {
        let history = items.filter { $0.pinboardID == nil }.sorted { $0.date > $1.date }
        items = history + items.filter { $0.pinboardID != nil }
        trim()
        save()
    }

    /// 同じ名前のピンボードがあれば色を合わせて返し、なければ作る
    func pinboard(named name: String, color: Int) -> Pinboard {
        guard let idx = pinboards.firstIndex(where: { $0.name == name }) else {
            return createPinboard(name: name, color: color)
        }
        if pinboards[idx].color != color {
            pinboards[idx].color = color
            savePinboards()
        }
        return pinboards[idx]
    }

    // MARK: - ファイル

    func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageName else { return nil }
        if let cached = imageCache.object(forKey: name as NSString) { return cached }
        guard let image = NSImage(contentsOf: imagesDir.appendingPathComponent(name)) else { return nil }
        imageCache.setObject(image, forKey: name as NSString)
        return image
    }

    /// 保存してある画像のファイル（引っぱり出し・シェア用）
    func imageURL(for item: ClipItem) -> URL? {
        item.imageName.map { imagesDir.appendingPathComponent($0) }
    }

    private func saveRaw(_ raw: RawPasteboard) -> String? {
        let encoder = PropertyListEncoder()
        encoder.outputFormat = .binary
        guard let data = try? encoder.encode(raw) else { return nil }
        let name = UUID().uuidString + ".plist"
        guard (try? data.write(to: rawDir.appendingPathComponent(name))) != nil else { return nil }
        return name
    }

    private func loadRaw(of item: ClipItem) -> RawPasteboard? {
        guard let name = item.rawName,
              let data = try? Data(contentsOf: rawDir.appendingPathComponent(name)) else { return nil }
        return try? PropertyListDecoder().decode(RawPasteboard.self, from: data)
    }

    private func duplicateRawFile(of item: ClipItem) -> String? {
        guard let name = item.rawName else { return nil }
        let copy = UUID().uuidString + ".plist"
        guard (try? FileManager.default.copyItem(at: rawDir.appendingPathComponent(name),
                                                 to: rawDir.appendingPathComponent(copy))) != nil else { return nil }
        return copy
    }

    private func removeFiles(of item: ClipItem) {
        removeImageFile(of: item)
        removeRawFile(of: item)
    }

    private func removeRawFile(of item: ClipItem) {
        guard let name = item.rawName else { return }
        try? FileManager.default.removeItem(at: rawDir.appendingPathComponent(name))
    }

    private func removeImageFile(of item: ClipItem) {
        guard let name = item.imageName else { return }
        // 同じ画像を参照している項目が他に残っていれば消さない
        if items.contains(where: { $0.imageName == name && $0.id != item.id }) { return }
        try? FileManager.default.removeItem(at: imagesDir.appendingPathComponent(name))
        imageCache.removeObject(forKey: name as NSString)
    }

    // MARK: - 保存

    private func load() {
        if let data = try? Data(contentsOf: historyURL),
           let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = decoded
        }
        if let data = try? Data(contentsOf: pinboardsURL),
           let decoded = try? JSONDecoder().decode([Pinboard].self, from: data) {
            pinboards = decoded
        }
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: historyURL, options: .atomic)
    }

    private func savePinboards() {
        guard let data = try? JSONEncoder().encode(pinboards) else { return }
        try? data.write(to: pinboardsURL, options: .atomic)
    }
}

extension NSImage {
    func pngData() -> Data? {
        guard let tiff = tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    var pixelSize: CGSize {
        if let rep = representations.first, rep.pixelsWide > 0 {
            return CGSize(width: rep.pixelsWide, height: rep.pixelsHigh)
        }
        return size
    }
}

/// 履歴の保存期間（Paste と同じ選択肢）
enum Retention: String, CaseIterable, Identifiable {
    case day, week, month, year, forever

    var id: String { rawValue }

    var title: String {
        switch self {
        case .day: "1日"
        case .week: "1週間"
        case .month: "1か月"
        case .year: "1年"
        case .forever: "無制限"
        }
    }

    var days: Int? {
        switch self {
        case .day: 1
        case .week: 7
        case .month: 30
        case .year: 365
        case .forever: nil
        }
    }

    static var current: Retention {
        get { UserDefaults.standard.string(forKey: "retention").flatMap(Retention.init(rawValue:)) ?? .forever }
        set { UserDefaults.standard.set(newValue.rawValue, forKey: "retention") }
    }
